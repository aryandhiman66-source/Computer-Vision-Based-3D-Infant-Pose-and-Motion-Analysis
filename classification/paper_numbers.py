"""Recompute every number used in the paper from the saved runs.

Writes paper/fact_sheet.md (tables of numbers + which runs they come from) and
paper/per_fold.csv. No prose: the text of the paper is written by the author.

Run:  C:/Users/aryan/miniconda3/python.exe classification/paper_numbers.py
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
from scipy.stats import t as tdist, wilcoxon

from analyse import RUNS, age, ba, load

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "paper"
B = 10000  # bootstrap resamples
rng = np.random.default_rng(0)


def infant(name):
    return re.match(r"(idxp\d+)", name).group(1)


def pooled(tags):
    """Per fold: (y, names, prob matrix [runs, clips], val_loss) pooled over tags."""
    folds = None
    for tag in tags:
        cur = [(d["y_test"], [str(n) for n in d["names_test"]],
                1 / (1 + np.exp(-d["test_logits"])), d["val_loss"]) for d in load(tag)]
        if folds is None:
            folds = cur
        else:
            folds = [(y, n, np.concatenate([p, p2]), np.concatenate([v, v2]))
                     for (y, n, p, v), (_, _, p2, v2) in zip(folds, cur)]
    return folds


def scores(tags):
    """Per-fold BA for paper rule / mean single run / ensemble + clip-level ensemble probs."""
    f = pooled(tags)
    paper = np.array([ba(y, p[np.argmin(v)], 0.5) for y, _, p, v in f])
    mean = np.array([np.mean([ba(y, r, 0.5) for r in p]) for y, _, p, _ in f])
    ens = np.array([ba(y, p.mean(0), 0.5) for y, _, p, _ in f])
    y = np.concatenate([d[0] for d in f])
    names = sum([d[1] for d in f], [])
    pe = np.concatenate([d[2].mean(0) for d in f])
    psingle = np.concatenate([d[2][np.argmin(d[3])] for d in f])
    return dict(paper=paper, mean=mean, ens=ens, y=y, names=names, pe=pe, psingle=psingle)


def t_ci(v):
    h = tdist.ppf(0.975, len(v) - 1) * v.std(ddof=1) / np.sqrt(len(v))
    return v.mean() - h, v.mean() + h


def infant_bootstrap(y, names, p, p_ref=None):
    """Cluster bootstrap over infants on pooled out-of-fold predictions."""
    inf = np.array([infant(n) for n in names])
    ids = np.unique(inf)
    idx = {i: np.where(inf == i)[0] for i in ids}
    stats, diffs = [], []
    for _ in range(B):
        s = np.concatenate([idx[i] for i in rng.choice(ids, len(ids))])
        stats.append(ba(y[s], p[s], 0.5))
        if p_ref is not None:
            diffs.append(stats[-1] - ba(y[s], p_ref[s], 0.5))
    out = dict(ci=np.percentile(stats, [2.5, 97.5]))
    if p_ref is not None:
        d = np.array(diffs)
        out.update(dci=np.percentile(d, [2.5, 97.5]), p_le0=(d <= 0).mean())
    return out


def discordant(y, names, p):
    young = np.array([age(n) < 50 for n in names])
    m = (young & (y == 1)) | (~young & (y == 0))
    return int(((p[m] > 0.5) == (y[m] == 1)).sum()), int(m.sum())


def pct(x):
    return f"{100 * x:.1f}"


def main():
    OUT.mkdir(exist_ok=True)
    rows = [  # (label, tags, source note)
        ("Faithful reproduction, seeds 0", ["paper_r8"], "runs/paper_r8 (8 runs/fold)"),
        ("Faithful reproduction, seeds 1", ["paper_r8_s1"], "runs/paper_r8_s1"),
        ("+ mirror/rotation aug, seeds 0", ["aug8_r8"], "runs/aug8_r8"),
        ("+ mirror/rotation aug, seeds 1", ["aug8_r8_s1"], "runs/aug8_r8_s1"),
        ("16 plain vs (row below)", ["paper_r8", "paper_r8_s1"], "paper_r8 + paper_r8_s1"),
        ("16 aug", ["aug8_r8", "aug8_r8_s1"], "aug8_r8 + aug8_r8_s1"),
        ("FINAL: 8 plain + 8 aug, fresh seeds", ["paper_r8_s1", "aug8_r8_s1"],
         "paper_r8_s1 + aug8_r8_s1 (pre-declared, Step 19)"),
        ("Same recipe, original seeds", ["paper_r8", "aug8_r8"], "paper_r8 + aug8_r8"),
    ]
    R = {lab: scores(tags) for lab, tags, _ in rows}

    L = ["# Fact sheet — numbers for the paper",
         "",
         "Generated by `classification/paper_numbers.py` from `classification/runs/`. "
         "Do not edit by hand; re-run the script. BA = balanced accuracy (%), 9 infant-wise folds "
         "(paper's split). *Paper rule* = the single run with lowest validation loss; *mean* = average "
         "single run; *ensemble* = averaged probabilities of all runs.",
         "",
         "## 1. Main table",
         "",
         "| model | runs/fold | paper rule | mean single | ensemble | ens. 95% t-CI (folds) | discordant clips | source |",
         "|---|---|---|---|---|---|---|---|"]
    for lab, tags, src in rows:
        s = R[lab]
        lo, hi = t_ci(s["ens"])
        h, n = discordant(s["y"], s["names"], s["pe"])
        nr = sum(load(t)[0]["test_logits"].shape[0] for t in tags)
        L.append(f"| {lab} | {nr} | {pct(s['paper'].mean())} | {pct(s['mean'].mean())} | "
                 f"{pct(s['ens'].mean())} | [{pct(lo)}, {pct(hi)}] | {h}/{n} | {src} |")
    L += ["", "Published reference (Kulvicius et al. 2025, video, best of 10 configs, best of 20 runs): "
          "**90.66**; mean of the 10 published configurations: **88.9** (Supp. Table 2/4).", ""]

    fin, ref = R["FINAL: 8 plain + 8 aug, fresh seeds"], R["Faithful reproduction, seeds 1"]
    plain16, aug16 = R["16 plain vs (row below)"], R["16 aug"]
    L += ["## 2. Statistical tests (paired over the 9 folds, two-sided Wilcoxon signed-rank)", "",
          "| comparison | mean diff (pts) | folds won | p |", "|---|---|---|---|"]
    for name, a, b in [("FINAL ensemble vs paper rule (same seeds 1)", fin["ens"], ref["paper"]),
                       ("16 aug vs 16 plain (ensembles)", aug16["ens"], plain16["ens"]),
                       ("aug paper-rule vs plain paper-rule (seeds 0)",
                        R["+ mirror/rotation aug, seeds 0"]["paper"],
                        R["Faithful reproduction, seeds 0"]["paper"])]:
        L.append(f"| {name} | {100 * (a - b).mean():+.2f} | {(a > b).sum()}/9 | "
                 f"{wilcoxon(a, b).pvalue:.3f} |")

    bs = infant_bootstrap(fin["y"], fin["names"], fin["pe"], ref["psingle"])
    pooled_ba = ba(fin["y"], fin["pe"], 0.5)
    L += ["", "## 3. Infant-level bootstrap (FINAL model, pooled out-of-fold predictions)", "",
          f"Resampling the 36 infants with replacement, {B} times (seed 0).", "",
          f"- pooled BA: {pct(pooled_ba)} (pooled over all clips; differs slightly from the fold mean)",
          f"- 95% CI: [{pct(bs['ci'][0])}, {pct(bs['ci'][1])}]",
          f"- difference vs paper-rule single model: 95% CI [{100 * bs['dci'][0]:+.1f}, "
          f"{100 * bs['dci'][1]:+.1f}] pts; fraction of resamples with no gain: {bs['p_le0']:.3f}",
          ""]

    L += ["## 4. Rejected / negative experiments (ensemble BA, for the 'what did not work' table)", "",
          "| experiment | tag | ensemble BA | matched baseline | diff vs baseline |", "|---|---|---|---|---|"]
    for lab, tags, bt in [("IMU auxiliary supervision", ["auximu_r8"], "paper_r8"),
                          ("temporal crop 4-5 s", ["aug8_crop200_r8"], "aug8_r8"),
                          ("limb-relative features", ["aug8_rel_r8"], "aug8_r8"),
                          ("paper configs 2,3,5,6,7,9,10 pooled",
                           [f"aug8_cfg{c}_r4" for c in (2, 3, 5, 6, 7, 9, 10)], "aug8_r8"),
                          ("extra 337 tuning clips (E5), seeds 0", ["aug8_extra_r8"], "aug8_r8"),
                          ("extra 337 tuning clips (E5), seeds 1", ["aug8_extra_r8_s1"], "aug8_r8_s1")]:
        if not all((RUNS / t / "fold9.npz").exists() for t in tags):
            L.append(f"| {lab} | {', '.join(tags)} | (not finished) | | |")
            continue
        e, base = scores(tags)["ens"], scores([bt])["ens"]
        L.append(f"| {lab} | {', '.join(tags)} | {pct(e.mean())} | {bt} {pct(base.mean())} | "
                 f"{100 * (e - base).mean():+.2f} (wins {(e > base).sum()}/9, p={wilcoxon(e, base).pvalue:.2f}) |")
    L += ["", "GBM sensor teacher (runs/teacher): 82.1 (from PROGRESS_LOG Step 13).", "",
          "## 5. Age confound (PROGRESS_LOG Step 10; separate analysis, not from these runs)", "",
          "- age-only oracle: 98.6", "- 14 static body numbers (proportions + pixel size, no motion): 90.5",
          "- proportions only: 75.4", "- hand-crafted motion statistics: 75.1", ""]
    (OUT / "fact_sheet.md").write_text("\n".join(L), encoding="utf-8")

    with open(OUT / "per_fold.csv", "w", encoding="utf-8") as fh:
        fh.write("model,metric," + ",".join(f"fold{k}" for k in range(1, 10)) + "\n")
        for lab, _, _ in rows:
            for m in ("paper", "mean", "ens"):
                fh.write(f"\"{lab}\",{m}," + ",".join(f"{100 * x:.2f}" for x in R[lab][m]) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
